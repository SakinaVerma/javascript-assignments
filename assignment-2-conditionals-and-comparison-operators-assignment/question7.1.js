let browser = 'firefox';

if (browser === 'chrome') {
    console.log('launch chrome');
}

if (browser === 'firefox') {
    console.log('launch firefox');
}

if (browser === 'edge') {
    console.log('launch edge');
} 
else {
    console.log('unsupported browser');
}

