let userName = "";
let userAge = 0;

if (userName === "") {
    console.log("empty username");
}

if (userAge === 0) {
    console.log("zero age");
}

if (userName == userAge) {
    console.log("username equals age");
}

if (userName === userAge) {
    console.log("username strictly equals age");
}

// Output: empty username
// zero age
// username equals age