let courseName = 'JavaScript';
let duration = 40;
let instructor = 'Naveen';

// Traditional concatenation
console.log(
  'Course: ' + courseName +
  ', Duration: ' + duration +
  ' hours, Instructor: ' + instructor
);

// Template literals
console.log(
  `Course: ${courseName}, Duration: ${duration} hours, Instructor: ${instructor}`
);

//Output : Course: JavaScript, Duration: 40 hours, Instructor: Naveen
//         Course: JavaScript, Duration: 40 hours, Instructor: Naveen