let character = "A";

if (character >= "A" && character <= "Z") {

    console.log("Uppercase Alphabet");

} else if (character >= "a" && character <= "z") {

    console.log("Lowercase Alphabet");

} else if (character >= "0" && character <= "9") {

    console.log("Digit");

} else {

    console.log("Special Character");

}