let browser = "Chrome";

switch (browser) {

    case "Chrome":
        console.log("Launching Chrome Browser");
        break;

    case "Firefox":
        console.log("Launching Firefox Browser");
        break;

    case "Edge":
        console.log("Launching Edge Browser");
        break;

    case "Safari":
        console.log("Launching Safari Browser");
        break;

    default:
        console.log("Invalid Browser");
}