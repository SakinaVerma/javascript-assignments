let rating = 5;

switch (rating) {

    case 5:
        console.log("20% Bonus");
        break;

    case 4:
        console.log("15% Bonus");
        break;

    case 3:
        console.log("10% Bonus");
        break;

    case 2:
        console.log("5% Bonus");
        break;

    case 1:
        console.log("No Bonus");
        break;

    default:
        console.log("Invalid Rating");
}