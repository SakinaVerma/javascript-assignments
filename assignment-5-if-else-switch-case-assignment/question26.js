let option = 2;

switch (option) {

    case 1:
        console.log("Check Balance");
        break;

    case 2:
        console.log("Withdraw Money");
        break;

    case 3:
        console.log("Deposit Money");
        break;

    case 4:
        console.log("Change PIN");
        break;

    case 5:
        console.log("Exit");
        break;

    default:
        console.log("Invalid Option");
}