let priority = 'high';

switch (priority) {
    case 'critical':
        console.log('critical priority');
        break;
    case 'high':
        console.log('high priority');
    case 'medium':
        console.log('medium priority');
        break;
    case 'low':
        console.log('low priority');
        break;
}

// Output:high priority
// medium priority

