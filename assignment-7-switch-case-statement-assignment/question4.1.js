let browser = 'opera';

switch (browser) {
    case 'chrome':
        console.log('chrome launched');
        break;
    case 'firefox':
        console.log('firefox launched');
        break;
    default:
        console.log('browser not in main list');
        break;

    case 'opera':
        console.log('opera launched');
        break;
    case 'safari':
        console.log('safari launched');
        break;
}

//Output : opera launched (Here Default location does not matter only matter is matching case )