//Spread Operator (...)

const arr1 = [1, 2, 3];
const arr2 = [4, 5, 6];

const combinedSpreadArray = [...arr1, ...arr2];

console.log(combinedSpreadArray);


//Using concat() Method

let arr3 = [1, 2, 3];
let arr4 = [4, 5, 6];

let combinedConcatArray = arr3.concat(arr4);

console.log(combinedConcatArray);