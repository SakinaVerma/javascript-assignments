//For Loop 

for (let i = 10; i >= 1; i--) {
    console.log("Numbers are : " + i);
}

// While loop

let j = 10;

while (j >= 1) {
    console.log(j);
    j--;

}

console.log("*******************************")

//Do While Loop 

let z = 10;

do {
    console.log("Using Do While Loop:" + z);
    z--;
} while (z >= 1);